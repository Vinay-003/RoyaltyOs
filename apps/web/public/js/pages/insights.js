import { api } from "../api.js";
import { shell } from "../nav.js";
import { state } from "../state.js";
import { esc, hero, money } from "../utils.js";

function auditSummary(audit) {
  if (!audit) return "Not verified yet.";
  const verified = Number(audit.verifiedEvents ?? 0);
  const legacy = Number(audit.legacyEvents ?? audit.legacy ?? 0);
  if (audit.valid) return `Chain valid — ${verified} verified, ${legacy} legacy (pre-chain).`;
  return `Chain BROKEN (${audit.reason ?? "unknown"}) — ${verified} verified before break, ${legacy} legacy.`;
}

function financialSummary(financial) {
  if (!financial) return "Not verified yet.";
  if (financial.valid) return `Balanced — ${Number(financial.openReconciliationIssues ?? 0)} open reconciliation issue(s).`;
  return `Mismatches: ${Number(financial.settlementMismatchCount ?? 0)} settlement(s), ${Number(financial.ledgerMismatchCount ?? 0)} ledger transaction(s), ${Number(financial.openReconciliationIssues ?? 0)} open issue(s).`;
}

export async function insights() {
  const d = await api(`/api/v1/insights?workspaceId=${state.workspaceId}`);
  const max = Math.max(1, ...(d.latestSettlement?.lines || []).map((x) => Number(x.amount_minor)));
  shell(
    `${hero("FINANCIAL INSIGHTS", "Revenue, settlement and reconciliation at a glance.", "Insights are computed from system-of-record data, not generated by the LLM.")}` +
      `<section class="metrics"><div class="metric"><span>Revenue</span><strong>${money(d.metrics.revenueMinor)}</strong></div>` +
      `<div class="metric"><span>Payout success</span><strong>${money(d.metrics.payoutSuccessMinor)}</strong></div>` +
      `<div class="metric"><span>Invoices</span><strong>${d.metrics.invoiceCount}</strong></div>` +
      `<div class="metric"><span>Active RuleSets</span><strong>${d.metrics.activeRulesetCount}</strong></div></section>` +
      `<div class="grid2"><section class="card"><div class="card-head"><div><div class="kicker">LATEST SETTLEMENT</div><h3>Allocation map</h3></div></div>` +
      `${d.latestSettlement?.lines?.length ? d.latestSettlement.lines.map((l) => `<div style="margin:10px 0"><div class="row" style="justify-content:space-between"><b>${esc(l.beneficiary_name)}</b><span class="amount">${money(l.amount_minor, d.latestSettlement.currency)}</span></div><div class="bar"><div style="width:${Number(l.amount_minor) / max * 100}%"></div></div><small>${esc(l.line_kind)} · payable ${money(l.payable_minor, d.latestSettlement.currency)}</small></div>`).join("") : `<div class="empty">No settlement lines yet.</div>`}` +
      `</section><section class="card"><div class="card-head"><div><div class="kicker">RECOUPMENT</div><h3>Advance recovery</h3></div></div>` +
      `${d.recoupments?.length ? d.recoupments.map((r) => `<div class="notice"><b>${esc(r.beneficiary_key)}</b><br>${money(r.recouped_minor, r.currency)} recouped of ${money(r.original_minor, r.currency)} · ${money(r.remaining_minor, r.currency)} remaining</div>`).join("<br>") : `<div class="empty">No active recoupment accounts.</div>`}` +
      `<br><div class="notice ${d.auditIntegrity?.valid ? "success" : "error"}">Audit: ${esc(auditSummary(d.auditIntegrity))}</div>` +
      `<br><div class="notice ${d.financialIntegrity?.valid ? "success" : "error"}">Financial integrity: ${esc(financialSummary(d.financialIntegrity))}</div>` +
      `${d.reconciliationIssues?.length ? `<h4>Open reconciliation issues</h4>${d.reconciliationIssues.map((i) => `<div class="notice error"><b>${esc(i.issue_type)}</b><br><small>${esc(i.severity)} · ${esc(i.resource_type)} ${esc(i.resource_id)}</small></div>`).join("")}` : ""}` +
      `</section></div>`,
    "Insights",
  );
}
